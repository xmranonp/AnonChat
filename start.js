'use strict';

// start.js — boots the node: writes the anon config, then starts server.js and the anon daemon.

const { spawn } = require('child_process');
const path = require('path');
const fs   = require('fs');

const proctree = require('./lib/proctree');
const netprefs = require('./lib/netprefs');
const { choosePorts } = require('./lib/ports');

const ROOT        = __dirname;
const PUBLIC_PORT = process.env.PUBLIC_PORT || 3000;
const UI_PORT     = process.env.UI_PORT     || 4000;
const ANON_DIR    = process.env.ANON_DIR || path.join(ROOT, 'anon');
const DATA_DIR    = process.env.DATA_DIR || path.join(ROOT, 'data');
const ANONRC      = path.join(ANON_DIR, 'anonrc');
const HOSTNAME    = path.join(ANON_DIR, 'anon_service', 'hostname');
const ANON_BIN    = process.env.ANON_BINARY || 'anon';
// Per-launch UI token: the desktop app passes its own; a standalone run makes one and prints a sign-in link for the browser.
const UI_TOKEN_GIVEN = typeof process.env.ANONCHAT_UI_TOKEN === 'string' && process.env.ANONCHAT_UI_TOKEN.length >= 32;
const UI_TOKEN = UI_TOKEN_GIVEN ? process.env.ANONCHAT_UI_TOKEN : require('crypto').randomBytes(32).toString('hex');
const UI_LINK  = UI_TOKEN_GIVEN ? `http://localhost:${UI_PORT}` : `http://localhost:${UI_PORT}/?t=${UI_TOKEN}`;

const children = [];
let poll = null;

// Keep the supervisor itself alive on stray errors — log, don't die silently.
process.on('unhandledRejection', (reason) => { console.error('[start] unhandledRejection:', reason); });
process.on('uncaughtException', (err) => { console.error('[start] uncaughtException:', err && err.stack ? err.stack : err); });

(async () => {
  const prefs = netprefs.load(DATA_DIR);
  const ports = await choosePorts({ dynamic: prefs.dynamicPort });
  if (ports.socksMoved) console.log(`  [net] SOCKS port 9050 is busy - using ${ports.socks} instead`);
  if (ports.socksBlocked) {
    console.error(`
  [error] SOCKS port 9050 is already in use and "Dynamic port" is off.
          Free the port, or turn "Dynamic port" on (Circuits tab) / delete
          ${path.join(DATA_DIR, 'network.json')} and start again.
`);
  }

  const anonDirForRc = path.isAbsolute(ANON_DIR) ? ANON_DIR : './anon';
  const serviceDir   = path.join(anonDirForRc, 'anon_service');
  fs.mkdirSync(ANON_DIR, { recursive: true, mode: 0o700 });
  fs.mkdirSync(DATA_DIR, { recursive: true, mode: 0o700 });
  // The country files that come with the Anyone release (geoip, geoip6) sit next to the anon binary in the packaged app. Without
  // these lines the Windows build looks for them in a folder that doesn't exist and warns at every start; Linux finds its own.
  const geoLines = [];
  if (path.isAbsolute(ANON_BIN)) {
    const g4 = path.join(path.dirname(ANON_BIN), 'geoip'), g6 = path.join(path.dirname(ANON_BIN), 'geoip6');
    if (fs.existsSync(g4)) geoLines.push(`GeoIPFile ${g4}`);
    if (fs.existsSync(g6)) geoLines.push(`GeoIPv6File ${g6}`);
  }
  fs.writeFileSync(ANONRC, `# Auto-generated by start.js
AgreeToTerms 1
ORPort 0
ControlPort ${ports.ctrl}
CookieAuthentication 1
SocksPort 127.0.0.1:${ports.socks}
SocksPolicy accept 127.0.0.1
SocksPolicy reject *
DataDirectory ${anonDirForRc}
HiddenServiceDir ${serviceDir}
HiddenServicePort 80 127.0.0.1:${PUBLIC_PORT}
# Traffic-analysis protection: dummy traffic on the link to the first relay always (the default pads only when the relay
# supports it); route padding and relays from distinct networks on each route, both defaults, stated so they stay on.
ConnectionPadding 1
CircuitPadding 1
EnforceDistinctSubnets 1
${geoLines.map((l) => l + '\n').join('')}`);

  const childEnv = {
    ...process.env, ANON_DIR, DATA_DIR,
    SOCKS: `socks5h://127.0.0.1:${ports.socks}`,
    ANON_CTRL_PORT: String(ports.ctrl),
  };
  delete childEnv.ANONCHAT_UI_TOKEN;          // only the backend gets the UI token, never the anon daemon
  delete childEnv.ANONCHAT_KEY_STDIN;         // nor the data key: the backend reads it from the stdin it shares with this process
  // In the packaged app the dependencies are staged as app_modules (electron-builder's extraResources would strip node_modules); NODE_PATH points there.
  const vendorModules = path.join(ROOT, 'app_modules');
  if (fs.existsSync(vendorModules)) {
    childEnv.NODE_PATH = childEnv.NODE_PATH
      ? vendorModules + path.delimiter + childEnv.NODE_PATH
      : vendorModules;
  }
  const serverEnv = { ...childEnv, ANONCHAT_UI_TOKEN: UI_TOKEN, NODE_ENV: 'production' };
  if (process.env.ANONCHAT_KEY_STDIN === '1') serverEnv.ANONCHAT_KEY_STDIN = '1';
  // Use process.execPath, not a bare 'node': it is the bundled runtime in the packaged app, and works when PATH has no node.
  const server = spawn(process.execPath, [path.join(ROOT, 'server.js')], { cwd: ROOT, stdio: 'inherit', windowsHide: true, env: serverEnv });
  children.push(server);
  // The backend stopping on its own (its port taken by another program, an unreadable data key…) stops the Anyone network program too:
  // the address must never stay published with nothing of ours behind it.
  server.on('exit', (code) => { if (!shuttingDown) shutdown(code || 1); });

  // Pipe anon's output so the UI can show it (/api/logs) while still echoing it to the console.
  const ANON_LOG = path.join(ANON_DIR, 'anon.log');
  const logStream = fs.createWriteStream(ANON_LOG, { flags: 'w' });
  const anon = spawn(ANON_BIN, ['-f', ANONRC], { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true, env: childEnv });
  if (anon.stdout) anon.stdout.on('data', c => { process.stdout.write(c); logStream.write(c); });
  if (anon.stderr) anon.stderr.on('data', c => { process.stderr.write(c); logStream.write(c); });
  children.push(anon);
  anon.on('error', (err) => {
    if (err.code === 'ENOENT') {
      console.error(`
  [error] Could not run '${ANON_BIN}' (not found).
    Download an anon binary (v0.4.10.2+) from:
      https://github.com/anyone-protocol/ator-protocol/releases
    then either put it on your PATH as 'anon', or:
      ANON_BINARY=/path/to/anon npm start
`);
    } else {
      console.error(`\n  [error] Failed to launch '${ANON_BIN}': ${err.message}\n`);
    }
    shutdown(1);
  });
  anon.on('exit', (code) => {
    if (code !== 0 && !printed) {
      console.error(`\n  [error] anon exited with code ${code} before publishing an address.\n`);
    }
  });

  let printed = false;
  poll = setInterval(() => {
    if (printed) return;
    try {
      const addr = fs.readFileSync(HOSTNAME, 'utf8').trim();
      if (!addr) return;
      printed = true;
      clearInterval(poll);
      const suffix = addr.split('.').pop();
      let suffixNote = '';
      if (suffix !== 'anyone') {
        suffixNote = `
  !  Address ends in .${suffix}, not .anyone.
     Your anon binary predates v0.4.10.2, or this key was generated by an
     older binary. Delete ./anon/anon_service/ and re-run with a v0.4.10.2+
     binary to mint a fresh .anyone address.
`;
      }
      console.log(`
  +-------------------------------------------------------------+
  |  You're live on the Anyone network.
  |
  |  Your identity (share this with contacts):
  |    ${addr}
  |
  |  Open your chat UI (this link changes every launch):
  |    ${UI_LINK}
  +-------------------------------------------------------------+
${suffixNote}`);
    } catch {}
  }, 1500);
})().catch((err) => {
  console.error('[start] launch failed:', err && err.stack ? err.stack : err);
  shutdown(1);
});

let shuttingDown = false;
async function shutdown(code = 0) {
  if (shuttingDown) return;
  shuttingDown = true;
  clearInterval(poll);
  clearInterval(parentWatch);
  await proctree.terminateChildren(children);
  process.exit(code);
}
process.on('SIGINT',  () => { console.log('\n  shutting down...'); shutdown(0); });
process.on('SIGTERM', () => shutdown(0));
process.on('SIGHUP',  () => shutdown(0));
process.on('exit', () => proctree.killChildrenSync(children));

// When launched by the desktop app, stop if the app disappears without telling
// us (crash, kill -9), so the anon daemon can't be orphaned.
const PARENT_PID = parseInt(process.env.ANONCHAT_PARENT_PID || '', 10);
const parentWatch = PARENT_PID > 0
  ? setInterval(() => {
      if (!proctree.pidAlive(PARENT_PID)) { console.log('\n  parent app exited, shutting down...'); shutdown(0); }
    }, 2000)
  : null;
