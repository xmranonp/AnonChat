// Builds public/emoji-names.js: an English name and search words for every emoji in the picker, from Unicode CLDR's English emoji
// annotations (unicode-org/cldr-json: cldr-annotations-full/annotations/en and cldr-annotations-derived-full/annotationsDerived/en).
// Run it again only when the emoji set changes:
//   node tools/build-emoji-names.mjs <annotations/en/annotations.json> <annotationsDerived/en/annotations.json>
// The window loads the result only when someone first types in the emoji search box; it never leaves the computer.

import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const [basePath, derivedPath] = process.argv.slice(2);
if (!basePath || !derivedPath) { console.error('usage: node tools/build-emoji-names.mjs <annotations.json> <annotationsDerived.json>'); process.exit(1); }

const base = JSON.parse(readFileSync(basePath, 'utf8')).annotations.annotations;
const derived = JSON.parse(readFileSync(derivedPath, 'utf8')).annotationsDerived.annotations;
const strip = (s) => s.replace(/️/g, '');
const table = new Map();
for (const src of [base, derived]) for (const [k, v] of Object.entries(src)) {
  const key = strip(k);
  if (!table.has(key)) table.set(key, v);
}

// public/*.js are browser modules; the project itself is CommonJS, so load a copy with the .mjs extension.
const tmp = join(mkdtempSync(join(tmpdir(), 'emoji-')), 'emoji-data.mjs');
writeFileSync(tmp, readFileSync(join(root, 'public/emoji-data.js')));
const { EMOJI_CATEGORIES } = await import(pathToFileURL(tmp).href);
const out = {};
const missing = [];
for (const cat of EMOJI_CATEGORIES) for (const e of cat.emojis) {
  const a = table.get(strip(e));
  if (!a) { missing.push(e); continue; }
  const name = (a.tts && a.tts[0]) || '';
  const words = new Set();
  for (const w of [name, ...(a.default || [])]) for (const part of w.toLowerCase().split(/[\s:,]+/)) if (part && part !== '|') words.add(part);
  // Stored as "name|word word word": the name for the tooltip, the words for matching.
  out[e] = name + '|' + [...words].join(' ');
}

const body = '// English names and search words for the emoji picker. Generated by tools/build-emoji-names.mjs from Unicode CLDR\n'
  + '// (unicode-org/cldr-json, Unicode License v3): edit the generator, not this file.\n\n'
  + 'export const EMOJI_NAMES = ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n';
writeFileSync(join(root, 'public/emoji-names.js'), body);
console.log(`named ${Object.keys(out).length} emojis, ${missing.length} without a name${missing.length ? ': ' + missing.join(' ') : ''}; ${body.length} bytes`);
